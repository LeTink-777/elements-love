export type ElementsInput = {
  me: ElementId;
  you: ElementId;
};

/**
 * Базовый тариф открывает разбор пары и сценарий конфликта; полный и премиум
 * добавляют разбор партнёра изнутри и инструкцию на 30 дней.
 */
function sectionCountForPlan(plan: PlanId): number {
  return plan === "basic" ? 3 : 5;
}

export function generateResultSections(
  input: ElementsInput,
  plan: string | null | undefined
): PdfSection[] {
  const resolvedPlan: PlanId = isPlanId(plan) ? plan : "full";
  const { me, you } = input;

  const score = getScore(me, you);
  const reading = getReading(me, you);
  const key = pairKey(me, you);

  const all: PdfSection[] = [
    {
      title: `${reading.title} — ${score} из 100`,
      content: `${getVerdict(score)}. Вы — ${ELEMENTS[me].name}, ваш партнёр — ${ELEMENTS[you].name}.\n\n${reading.summary}`,
    },
    {
      title: "Сильная сторона пары",
      content: reading.strength,
    },
    {
      title: "Сценарий вашего конфликта",
      content: `${reading.risk}\n\n${CONFLICT[key]}`,
    },
    {
      title: "Что чувствует ваш человек",
      content: INNER[you],
    },
    {
      title: "Инструкция на 30 дней",
      content: PLAN30[key],
    },
  ];

  return all.slice(0, sectionCountForPlan(resolvedPlan));
}

/** Читает пару стихий из metadata ЮKassa — там всё приходит строками. */
export function inputFromMetadata(
  metadata: Record<string, string>
): ElementsInput | null {
  if (!isElementId(metadata.me) || !isElementId(metadata.you)) return null;
  return { me: metadata.me, you: metadata.you };
}

/** Строка под заголовком отчёта: пара стихий. */
export function buildSubtitle(input: ElementsInput): string {
  return `${ELEMENTS[input.me].name} и ${ELEMENTS[input.you].name}`;
}
