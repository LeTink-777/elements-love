export function getVerdict(score: number): string {
  if (score >= 90) return "Редкое совпадение";
  if (score >= 80) return "Сильная пара";
  if (score >= 70) return "Рабочее сочетание";
  if (score >= 60) return "Требует усилий";
  return "Проверка на прочность";
}

