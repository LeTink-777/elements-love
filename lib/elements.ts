export const ELEMENT_ORDER: ElementId[] = ["fire", "water", "earth", "air"];

export function isElementId(value: unknown): value is ElementId {
  return value === "fire" || value === "water" || value === "earth" || value === "air";
}

const SCORES: Record<string, number> = {
  "fire|air": 95,
  "fire|fire": 70,
  "fire|water": 45,
  "fire|earth": 65,
  "water|water": 80,
  "water|earth": 90,
  "water|air": 60,
  "earth|earth": 75,
  "earth|air": 70,
  "air|air": 85,
};

export function getScore(a: ElementId, b: ElementId): number {
  const direct = SCORES[`${a}|${b}`];
  if (typeof direct === "number") return direct;
  const reversed = SCORES[`${b}|${a}`];
  return typeof reversed === "number" ? reversed : 70;
}

